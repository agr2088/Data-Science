"""
============================================================
Pipeline Artifact Entities
Bankruptcy Risk Intelligence System
============================================================

Purpose
-------
This module defines artifact objects used to pass outputs
between different stages of the machine learning pipeline.

Artifacts represent the result produced by one pipeline stage
which becomes the input for the next stage.

Why Artifacts Are Important
---------------------------
Using artifact entities provides several benefits:

• Clean communication between pipeline stages
• Strongly typed pipeline outputs
• Easier debugging and pipeline monitoring
• Clear representation of pipeline data flow

Pipeline Data Flow
------------------

Data Ingestion
      ↓
DataIngestionArtifact
      ↓
Data Validation
      ↓
DataValidationArtifact
      ↓
Data Transformation
      ↓
DataTransformationArtifact
      ↓
Model Training
      ↓
ModelTrainerArtifact

Each artifact object stores the outputs generated by a
pipeline component.
"""

# ==========================================================
# 1. IMPORT REQUIRED LIBRARY
# ==========================================================

from dataclasses import dataclass


# ==========================================================
# 2. DATA INGESTION ARTIFACT
# ==========================================================

@dataclass
class DataIngestionArtifact:
    """
    Artifact produced by the Data Ingestion stage.

    Attributes
    ----------
    train_file_path : str
        File path of the generated training dataset.

    test_file_path : str
        File path of the generated testing dataset.
    """

    train_file_path: str
    test_file_path: str


# ==========================================================
# 3. DATA VALIDATION ARTIFACT
# ==========================================================

@dataclass
class DataValidationArtifact:
    """
    Artifact produced by the Data Validation stage.

    Attributes
    ----------
    validation_status : bool
        Indicates whether dataset validation succeeded.

    message : str
        Detailed validation result message.

    status_file_path : str
        File path where validation status is stored.
    """

    validation_status: bool
    message: str
    status_file_path: str


# ==========================================================
# 4. DATA TRANSFORMATION ARTIFACT
# ==========================================================

@dataclass
class DataTransformationArtifact:
    """
    Artifact produced by the Data Transformation stage.

    Attributes
    ----------
    transformed_train_file_path : str
        File path of transformed training feature dataset.

    transformed_test_file_path : str
        File path of transformed testing feature dataset.

    transformed_y_train_file_path : str
        File path of transformed training target labels.

    transformed_y_test_file_path : str
        File path of transformed testing target labels.
    """

    transformed_train_file_path: str
    transformed_test_file_path: str
    transformed_y_train_file_path: str
    transformed_y_test_file_path: str


# ==========================================================
# 5. MODEL TRAINER ARTIFACT
# ==========================================================

@dataclass
class ModelTrainerArtifact:
    """
    Artifact produced by the Model Training stage.

    Attributes
    ----------
    trained_model_file_path : str
        File path where the trained model is saved.

    test_accuracy : float
        Accuracy score achieved on the test dataset.

    test_auc : float
        ROC-AUC score on the test dataset.

    cv_auc : float
        Cross-validation ROC-AUC score obtained during
        model training.
    """

    trained_model_file_path: str
    test_accuracy: float
    test_auc: float
    cv_auc: float