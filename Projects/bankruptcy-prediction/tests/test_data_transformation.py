"""
============================================================
Data Transformation Tests
Bankruptcy Risk Intelligence System
============================================================

Purpose
-------
This test module verifies that the Data Transformation
component correctly processes the dataset generated by
the Data Ingestion stage.

The transformation stage prepares the dataset for
machine learning model training.

Why This Test Matters
---------------------
The transformation stage performs critical operations:

• separating features and target variable
• encoding the target labels
• generating model-ready datasets

Any mistake in this stage could cause model training
to fail or produce incorrect results.
"""

# ==========================================================
# IMPORT REQUIRED MODULES
# ==========================================================

import os
import pandas as pd

from bankruptcy.config.configuration import ConfigurationManager
from bankruptcy.components.data_ingestion import DataIngestion
from bankruptcy.components.data_transformation import DataTransformation


# ==========================================================
# TEST: DATA TRANSFORMATION PIPELINE
# ==========================================================

def test_data_transformation_runs_successfully():
    """
    Verify that the transformation pipeline:

    • runs without errors
    • generates transformed artifacts
    • separates features and target
    • encodes target labels correctly
    • preserves dataset row counts
    """

    config_manager = ConfigurationManager()


    # ======================================================
    # 1️⃣ RUN DATA INGESTION
    # ======================================================

    ingestion_config = config_manager.get_data_ingestion_config()

    ingestion = DataIngestion(ingestion_config)

    ingestion_artifact = ingestion.initiate_data_ingestion()

    train_df = pd.read_csv(ingestion_artifact.train_file_path)

    test_df = pd.read_csv(ingestion_artifact.test_file_path)


    # ======================================================
    # 2️⃣ RUN DATA TRANSFORMATION
    # ======================================================

    transformation_config = config_manager.get_data_transformation_config()

    transformation = DataTransformation(
        ingestion_artifact,
        transformation_config
    )

    transformation_artifact = transformation.initiate_data_transformation()


    # ======================================================
    # 3️⃣ VERIFY TRANSFORMATION ARTIFACT FILES EXIST
    # ======================================================

    assert os.path.exists(
        transformation_artifact.transformed_train_file_path
    )

    assert os.path.exists(
        transformation_artifact.transformed_test_file_path
    )

    assert os.path.exists(
        transformation_artifact.transformed_y_train_file_path
    )

    assert os.path.exists(
        transformation_artifact.transformed_y_test_file_path
    )


    # ======================================================
    # 4️⃣ LOAD TRANSFORMED DATASETS
    # ======================================================

    X_train = pd.read_csv(
        transformation_artifact.transformed_train_file_path
    )

    X_test = pd.read_csv(
        transformation_artifact.transformed_test_file_path
    )

    y_train = pd.read_csv(
        transformation_artifact.transformed_y_train_file_path
    )

    y_test = pd.read_csv(
        transformation_artifact.transformed_y_test_file_path
    )


    # ======================================================
    # 5️⃣ VERIFY TARGET COLUMN REMOVED FROM FEATURES
    # ======================================================

    assert "class" not in X_train.columns

    assert "class" not in X_test.columns


    # ======================================================
    # 6️⃣ VERIFY TARGET ENCODING (0 / 1)
    # ======================================================

    assert set(y_train.iloc[:, 0].unique()).issubset({0, 1})

    assert set(y_test.iloc[:, 0].unique()).issubset({0, 1})


    # ======================================================
    # 7️⃣ VERIFY DATASET ROW CONSISTENCY
    # ======================================================

    assert len(X_train) == len(y_train) == len(train_df)

    assert len(X_test) == len(y_test) == len(test_df)